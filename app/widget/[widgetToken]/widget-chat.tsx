interface MessageRowProps {
  message: Message
  // Result payloads for this message's tool calls, keyed by toolCallId.
  toolResults: Record<string, string>
  canReply: boolean
  // The workspace's logo for the avatar beside the reply, or null for the answerLoops mark.
  logoUrl: string | null
  // Set only when this reply can be flagged: the page's flagging settings and
  // the signed reference the server gave for this answer.
  feedback: AnswerFeedbackConfig | null
  answerToken: string | null
}

/**
 * One chat row. Memoised: while a reply streams, only the message being
 * written changes, so every earlier row (and its cards) can skip re-rendering
 * instead of the whole thread re-rendering on each token.
 */
const MessageRow = memo(
  function MessageRow({ message, toolResults, logoUrl, feedback, answerToken }: MessageRowProps) {
    const renderToolCall = useRenderToolCall()

    if (message.role === 'user') {
      return (
        <div className="flex justify-end">
          <div className="max-w-[80%] rounded-2xl rounded-br-sm bg-brand-600 px-3 py-2 text-xs leading-relaxed whitespace-pre-wrap break-words text-on-brand">
            {typeof message.content === 'string' ? message.content : ''}
          </div>
        </div>
      )
    }
    if (message.role !== 'assistant') return null

    const text = typeof message.content === 'string' ? message.content : ''
    const cards: ReactElement[] = []
    for (const toolCall of (message.toolCalls ?? []) as ToolCallLike[]) {
      const result = toolResults[toolCall.id]
      const rendered = renderToolCall({
        toolCall,
        toolMessage: result === undefined ? undefined : { id: `${toolCall.id}-result`, role: 'tool', toolCallId: toolCall.id, content: result },
      })
      if (rendered) cards.push(<div key={toolCall.id} className="flex justify-start">{rendered}</div>)
    }
    if (!text && cards.length === 0) return null

    return (
      <>
        {text && (
          <div className="flex justify-start">
            <AssistantAvatar logoUrl={logoUrl} />
            <div className="max-w-[80%] rounded-2xl rounded-bl-sm bg-gray-100 px-3 py-2 text-xs leading-relaxed break-words text-gray-800">
              <ChatMarkdown text={text} />
            </div>
          </div>
        )}
        {text && feedback && answerToken && <AnswerFeedback config={feedback} answerToken={answerToken} />}
        {cards.length > 0 && <div className="space-y-2 pl-8">{cards}</div>}
      </>
    )
  },
  (prev, next) => {
    if (prev.canReply !== next.canReply || prev.logoUrl !== next.logoUrl) return false
    if (prev.feedback !== next.feedback || prev.answerToken !== next.answerToken) return false
    if (prev.message === next.message && prev.toolResults === next.toolResults) return true
    const a = prev.message
    const b = next.message
    if (a.id !== b.id || a.role !== b.role || a.content !== b.content) return false
    const ac = a.role === 'assistant' ? (a.toolCalls ?? []) : []
    const bc = b.role === 'assistant' ? (b.toolCalls ?? []) : []
    if (ac.length !== bc.length) return false
    return ac.every(
      (call, i) => call.id === bc[i].id && call.function.arguments === bc[i].function.arguments && prev.toolResults[call.id] === next.toolResults[call.id]
    )
  }
)

interface StoredChat {
  /** True once this browser's storage has been read (never on the server). */
  loaded: boolean
  /** The conversation saved by an earlier visit, within its time limit. */
  restored: Message[]
  /** A question held for an automatic resend after a reload, if any. */
  pending: string | null
}

const NOT_LOADED: StoredChat = { loaded: false, restored: [], pending: null }

function readStoredChat(widgetToken: string): StoredChat {
  return { loaded: true, restored: loadTranscript(widgetToken), pending: takePending(widgetToken) }
}

const subscribeNever = () => () => {}
const readStoredOnServer = () => NOT_LOADED

