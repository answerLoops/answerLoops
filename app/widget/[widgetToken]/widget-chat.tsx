function WidgetChatBody({
  widgetToken,
  renderToken,
  orgName,
  showBranding,
  visitorId,
  isSelfPreview,
  leadCaptureMode,
  title,
  welcome,
  starterQuestions,
  logoUrl,
  brandStyle,
  answerFlagsEnabled,
}: {
  widgetToken: string
  renderToken: string
  orgName: string
  showBranding: boolean
  visitorId: string
  isSelfPreview: boolean
  leadCaptureMode: WidgetLeadCaptureMode
  title: string | null
  welcome: string | null
  starterQuestions: string[]
  logoUrl: string | null
  brandStyle: Record<string, string> | null
  answerFlagsEnabled: boolean
}) {
  const bottomRef = useRef<HTMLDivElement>(null)
  const [input, setInput] = useState('')
  const [email, setEmail] = useState('')
  // 'up-front' starts gated (the original hardcoded behaviour); 'off' and
  // 'on-failure' both let the visitor straight into the conversation — they
  // differ only in whether a prompt can appear later. leadCaptureMode is a
  // prop from the server and does not change during the widget's life.
  const [emailSubmitted, setEmailSubmitted] = useState(leadCaptureMode !== 'up-front')
  const [emailPending, setEmailPending] = useState(false)
  const [emailError, setEmailError] = useState('')

  // The on-failure prompt: which signal triggered it (null = not showing),
  // and whether the visitor has already acted on one this conversation
  // (submitted or dismissed) so repeated failures don't keep re-asking.
  // Typed without 'none' so a truthy check can't accidentally let it through
  // — the string 'none' is itself truthy.
  // questionToken is the server-signed copy of the question that failed (see
  // lib/widget/lead-question-token.ts), handed back with the email so the lead
  // carries what the server recorded rather than client-typed text.
  const [failurePrompt, setFailurePrompt] = useState<{
    signal: Exclude<WidgetLeadSignal, 'none'>
    questionToken?: string
  } | null>(null)
  const [leadHandled, setLeadHandled] = useState(false)
  const [failureEmail, setFailureEmail] = useState('')
  const [failureEmailPending, setFailureEmailPending] = useState(false)
  const [failureEmailError, setFailureEmailError] = useState('')
  // The id of the message most recently sent, generated per send. The server
  // records each turn's result under it, and a lookup only ever applies if its
  // turn is still the latest one — see checkLeadSignal. A ref, not state:
  // nothing in the UI needs to re-render on it.
  const currentTurnRef = useRef('')
  // The signed reference to each answer this page has seen the server record,
  // keyed by the reply's message id; only an answer with one shows the thumbs
  // (lib/widget/answer-token.ts). Never saved with the conversation, so a reply
  // restored from an earlier visit has none and shows no thumbs.
  const [answerTokens, setAnswerTokens] = useState<Record<string, string>>({})

  const { agent } = useAgent()
  // What this browser saved of an earlier conversation. Read through the
  // external-store hook so the server-rendered page (which has no browser
  // storage) and the first client render agree, then the client updates.
  const storedRef = useRef<StoredChat | null>(null)
  const readStored = useCallback(() => (storedRef.current ??= readStoredChat(widgetToken)), [widgetToken])
  const stored = useSyncExternalStore(subscribeNever, readStored, readStoredOnServer)
  const ready = stored.loaded
  // The conversation as drawn: whatever has happened in this page since it
  // opened, else the restored one.
  const [liveMessages, setMessages] = useState<Message[] | null>(null)
  const messages = liveMessages ?? (stored.restored.length > 0 ? stored.restored : agent.messages)
  // Whether the restored thread has been given to the agent yet (done just
  // before the first message is sent, so the agent sends the full thread).
  const seededRef = useRef(false)
  const [isLoading, setIsLoading] = useState(false)
  const [error, setError] = useState<string | null>(null)
  // The chat call is refused (HTTP 403) once the page's short-lived pass has
  // expired, which is what happens when a visitor leaves the chat open and
  // comes back. Reloading the panel gets a fresh one.
  const [sessionExpired, setSessionExpired] = useState(false)
  // True from the moment an automatic reload begins, so nothing re-saves the
  // conversation with the unanswered question in it while the page goes away.
  const recoveringRef = useRef(false)

  const checkLeadSignal = useCallback(async () => {
    // The same post-turn lookup serves two things: the on-failure prompt, and
    // the signed reference that lets the visitor flag the answer just given.
    // Each only applies when its own condition holds; with neither, no request.
    const wantLead = leadCaptureMode === 'on-failure' && !leadHandled
    const wantFlag = answerFlagsEnabled
    if (!wantLead && !wantFlag) return
    // The turn this lookup is for. If the visitor sends another message while
    // a slow lookup (or one of its retries) is still in flight, its result is
    // about a turn that is already over and must not touch the screen.
    const turnId = currentTurnRef.current
    if (!turnId) return
    for (let attempt = 0; attempt < LEAD_SIGNAL_MAX_ATTEMPTS; attempt++) {
      const isLastAttempt = attempt === LEAD_SIGNAL_MAX_ATTEMPTS - 1
      try {
        const res = await fetch('/api/widget/lead-signal', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ widgetToken, renderToken, visitorId, turnId }),
        })
        if (res.status === 429) {
          if (isLastAttempt) return // Retries exhausted: leave existing state — see below.
          await sleep(LEAD_SIGNAL_RETRY_DELAY_MS * (attempt + 1))
          continue
        }
        if (!res.ok) return
        const data: unknown = await res.json()
        const signal = (data as { signal?: unknown })?.signal
        const questionToken = (data as { questionToken?: unknown })?.questionToken
        const answerToken = (data as { answerToken?: unknown })?.answerToken
        if (!isWidgetLeadSignal(signal)) return
        if (currentTurnRef.current !== turnId) return
        // A definitive 'none' clears any prompt left showing from an earlier
        // call in this same retry loop; any other signal shows its prompt.
        // Deliberately not reached on a retry-exhausted network error below
        // — an indefinite result should never overwrite a real prompt that's
        // already showing just because this one poll couldn't confirm it.
        if (wantLead) {
          setFailurePrompt(
            signal === 'none'
              ? null
              : { signal, ...(typeof questionToken === 'string' ? { questionToken } : {}) }
          )
        }
        // The reply this turn produced is the newest assistant message with
        // text. Without one (or without a token: the server's short-lived note
        // of the turn can be missed) that answer simply has no thumbs.
        if (wantFlag && typeof answerToken === 'string') {
          const reply = [...agent.messages]
            .reverse()
            .find((m) => m.role === 'assistant' && typeof m.content === 'string' && m.content.length > 0)
          if (reply) setAnswerTokens((prev) => (prev[reply.id] ? prev : { ...prev, [reply.id]: answerToken }))
        }
        return
      } catch {
        if (isLastAttempt) return // Retries exhausted: leave existing state, don't guess.
        await sleep(LEAD_SIGNAL_RETRY_DELAY_MS * (attempt + 1))
      }
    }
  }, [leadCaptureMode, leadHandled, answerFlagsEnabled, agent, widgetToken, renderToken, visitorId])

  useEffect(() => {
    // `messages` starts as agent.messages (see the useState above) and every
    // later change arrives through this subscription, so there is nothing to
    // copy in here.
    const { unsubscribe } = agent.subscribe({
      onEvent: ({ messages: current }) => setMessages([...current]),
      onRunInitialized: () => {
        setError(null)
        setIsLoading(true)
      },
      onRunFinalized: () => {
        setIsLoading(false)
        // A failed run never reaches the chat route's onFinish, so the stash
        // this reads has nothing for it — the fetch above just resolves to
        // 'none' and the prompt stays hidden. Safe to call unconditionally.
        void checkLeadSignal()
      },
      // The server only puts a specific message in error.message when
      // isSelfPreview asked for one — see app/api/widget/chat/route.ts.
      // Real customer-site visitors get the generic fallback below.
      onRunFailed: ({ error: runError }) => {
        setIsLoading(false)
        if (/^HTTP 403\b/.test(runError.message)) {
          setError(null)
          // The page's short-lived pass ran out while the chat sat open. Get a
          // fresh one without the visitor having to do anything: remember the
          // question, reload the chat, and send it again. Only if that has
          // just been tried (or storage is blocked) is the visitor asked to
          // start a new session.
          const thread = agent.messages
          const lastUser = thread.map((m) => m.role).lastIndexOf('user')
          const question = lastUser === -1 ? undefined : thread[lastUser].content
          if (typeof question === 'string' && beginRecovery(widgetToken, question)) {
            recoveringRef.current = true
            saveTranscript(widgetToken, thread.slice(0, lastUser))
            window.location.reload()
            return
          }
          setSessionExpired(true)
          return
        }
        // Strip the "HTTP 503: " transport prefix the AG-UI client adds —
        // only the server's own message text is meant for display.
        const message = runError.message.replace(/^HTTP \d+:\s*/, '')
        setError(message || 'Something went wrong. Please try again.')
      },
    })
    return unsubscribe
  }, [agent, checkLeadSignal, widgetToken])

  // Keep the conversation once a turn is finished (not on every streamed token).
  useEffect(() => {
    if (!ready || isLoading || recoveringRef.current) return
    // Nothing has happened since the restore: nothing new to keep, and merely
    // opening the chat must not extend how long it is kept.
    if (liveMessages === null) return
    saveTranscript(widgetToken, liveMessages)
  }, [ready, isLoading, liveMessages, widgetToken])

  useEffect(() => {
    // Smooth scrolling restarts its animation on every streamed token and
    // visibly lags behind the text; jump while a reply is arriving.
    bottomRef.current?.scrollIntoView({ behavior: isLoading ? 'auto' : 'smooth' })
  }, [messages, isLoading, failurePrompt])

  useGenuiRenderers()

  const toolResultsByMessage = useMemo(() => {
    const byCallId: Record<string, string> = {}
    for (const m of messages) {
      if (m.role === 'tool' && typeof m.content === 'string') byCallId[m.toolCallId] = m.content
    }
    const out = new Map<string, Record<string, string>>()
    for (const m of messages) {
      if (m.role !== 'assistant' || !m.toolCalls?.length) continue
      out.set(m.id, Object.fromEntries(m.toolCalls.filter((c) => c.id in byCallId).map((c) => [c.id, byCallId[c.id]])))
    }
    return out
  }, [messages])

  const sendMessage = useCallback(
    (raw: string) => {
      const text = raw.trim()
      if (!text || isLoading) return
      // Visual only — leadHandled is untouched, so a later real failure can
      // still show a fresh prompt. Without this, a stale "couldn't help"
      // card from an earlier turn stays on screen under this turn's answer,
      // even once that answer actually helps.
      setFailurePrompt(null)
      const turnId = crypto.randomUUID()
      currentTurnRef.current = turnId
      if (!seededRef.current) {
        seededRef.current = true
        if (stored.restored.length > 0 && agent.messages.length === 0) agent.setMessages(stored.restored)
      }
      agent.addMessage({ id: crypto.randomUUID(), role: 'user', content: text })
      // Every run sends the whole thread and the endpoint refuses more than 50
      // messages, so a long conversation (or a restored one) keeps only its
      // newest messages.
      const thread = trimForRequest(agent.messages as Message[])
      if (thread.length !== agent.messages.length) agent.setMessages(thread)
      // addMessage() only mutates the agent's local message list — our
      // `messages` state otherwise only updates from server-pushed onEvent
      // data, so without this the user's own bubble disappears for the whole
      // request round-trip (reappearing only once the server echoes it back).
      setMessages([...agent.messages])
      // agent.runAgent() called bare skips CopilotKitCore's forwardedProps merge
      // (that only happens inside copilotkit.runAgent()) — pass widgetToken and
      // visitorId explicitly or the server never sees them.
      void agent.runAgent({ forwardedProps: { widgetToken, renderToken, visitorId, turnId, isSelfPreview } })
    },
    [agent, isLoading, stored, widgetToken, renderToken, visitorId, isSelfPreview]
  )

  // What every reply's thumbs need. A stable object, so rows that did not change
  // are not redrawn; null when flagging is off. The email field is only offered
  // when the owner has not switched email follow-up off.
  const feedbackConfig = useMemo<AnswerFeedbackConfig | null>(
    () => (answerFlagsEnabled ? { widgetToken, renderToken, offerEmail: leadCaptureMode !== 'off' } : null),
    [answerFlagsEnabled, widgetToken, renderToken, leadCaptureMode]
  )

  // Follow-up suggestions are pressable only under the newest reply, before the
  // visitor has typed or answered, and never from a conversation restored from
  // an earlier visit.
  const restoredFollowUpIds = useMemo(() => followUpCallIds(stored.restored), [stored.restored])
  const liveFollowUpId = useMemo(() => latestFollowUpCallId(messages), [messages])
  const activeFollowUpId =
    !isLoading && input.trim() === '' && liveFollowUpId && !restoredFollowUpIds.has(liveFollowUpId) ? liveFollowUpId : null
  const actions = useMemo(
    () => ({ send: sendMessage, canReply: !isLoading, activeFollowUpId }),
    [sendMessage, isLoading, activeFollowUpId]
  )

  // After a reload caused by a refused call, send the held question once.
  const resentRef = useRef(false)
  useEffect(() => {
    if (!ready || !stored.pending || resentRef.current) return
    resentRef.current = true
    sendMessage(stored.pending)
  }, [ready, stored, sendMessage])

  function handleNewChat() {
    recoveringRef.current = true
    startNewChat(widgetToken)
    window.location.reload()
  }

  function handleSubmit(e: React.FormEvent) {
    e.preventDefault()
    if (!input.trim() || isLoading) return
    setInput('')
    sendMessage(input)
  }

  // Every non-'ok' outcome is reported to the visitor and leaves them where
  // they are, so a lead is never dropped without them seeing it. At the
  // up-front gate that is not a dead end: Skip is always visible beside the
  // form, so a visitor the server keeps turning away can still get into the
  // chat.
  async function postLead(
    address: string,
    questionToken?: string
  ): Promise<'ok' | 'invalid' | 'rate-limited' | 'network-error'> {
    if (!address.trim()) return 'ok'
    try {
      const res = await fetch('/api/widget/lead', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ widgetToken, renderToken, email: address.trim(), ...(questionToken ? { questionToken } : {}) }),
      })
      if (res.ok) return 'ok'
      return res.status === 429 ? 'rate-limited' : 'invalid'
    } catch {
      return 'network-error'
    }
  }

  async function handleEmailSubmit(e: React.FormEvent) {
    e.preventDefault()
    if (!email.trim()) { setEmailSubmitted(true); return }
    setEmailPending(true)
    setEmailError('')
    const result = await postLead(email)
    setEmailPending(false)
    if (result !== 'ok') {
      setEmailError(
        result === 'invalid'
          ? "That didn't go through — check the address and try again, or Skip."
          : "We couldn't save that right now — try again in a moment, or Skip."
      )
      return
    }
    setEmailSubmitted(true)
  }

  async function handleFailurePromptSubmit(e: React.FormEvent) {
    e.preventDefault()
    setFailureEmailPending(true)
    setFailureEmailError('')
    const result = await postLead(failureEmail, failurePrompt?.questionToken)
    setFailureEmailPending(false)
    if (result !== 'ok') {
      setFailureEmailError(
        result === 'rate-limited'
          ? "That's one too many tries — wait a moment and try again, or No thanks to skip."
          : "That didn't go through — try again, or No thanks to skip."
      )
      return
    }
    setFailurePrompt(null)
    setLeadHandled(true)
  }

  function dismissFailurePrompt() {
    setFailurePrompt(null)
    setLeadHandled(true)
  }

  // A visitor with a conversation (or one being recovered) has already been
  // through the email screen.
  const gatePassed = emailSubmitted || stored.restored.length > 0 || stored.pending !== null

  const lastMessage = messages[messages.length - 1]
  // The dots only fill the gap before the reply starts; once text or a card
  // is streaming, the message itself is the progress indicator.
  const showTyping = isLoading && (!lastMessage || lastMessage.role !== 'assistant')

  return (
    <WidgetActionsProvider value={actions}>
    <div
      className="flex flex-col h-screen bg-white font-sans text-sm"
      // Only generated #rrggbb tokens from brandPalette() reach this style.
      style={brandStyle ? (brandStyle as CSSProperties) : undefined}
      data-brand-colored={brandStyle ? 'true' : undefined}
    >
      {/* Header */}
      <div className="flex items-center gap-2.5 px-4 py-3 border-b border-gray-100 bg-white shrink-0">
        {/* A light tint of the brand color, like the reply avatars: the logo mark is dark,
              so it stays visible on any brand color, including a very dark one. */}
        <LogoAvatar logoUrl={logoUrl} size={28} testId="header-avatar" />
        <div className="min-w-0 flex-1">
          <p className="font-semibold text-gray-900 text-sm truncate">{title ?? `${orgName} Support`}</p>
          <p className="text-xs text-green-500 font-medium">Online</p>
        </div>
        {ready && messages.length > 0 && (
          <button
            type="button"
            onClick={handleNewChat}
            aria-label="New chat"
            className="-my-2 -mr-2 flex min-h-11 min-w-11 shrink-0 items-center justify-center gap-1.5 rounded-lg px-2.5 text-xs font-medium text-gray-500 hover:bg-gray-50 hover:text-gray-800 focus:outline-none focus-visible:ring-2 focus-visible:ring-brand-400 transition-colors"
          >
            <svg className="h-3.5 w-3.5" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
              <path d="M12 5v14M5 12h14" />
            </svg>
            {/* On a very narrow chat only the icon shows, so the title keeps its room; the button's name is unchanged. */}
            <span className="max-[300px]:hidden">New chat</span>
          </button>
        )}
      </div>

      {/* Nothing below until this browser's saved conversation has been read. */}
      {!ready ? (
        <div className="flex-1" />
      ) : /* Email gate — shown before first message if email not submitted */
      !gatePassed ? (
        <div className="flex flex-1 flex-col items-center justify-center px-6 py-8 text-center">
          <div className="mb-4">
            <WelcomeAvatar logoUrl={logoUrl} />
          </div>
          <h2 className="text-sm font-semibold text-gray-900 mb-1 break-words">{welcome ?? '👋 Hi! How can we help?'}</h2>
          <p className="text-xs text-gray-400 mb-6">Drop your email to get started — we&apos;ll follow up if needed.</p>
          <form onSubmit={handleEmailSubmit} className="w-full space-y-3">
            <input
              type="email"
              value={email}
              onChange={(e) => setEmail(e.target.value)}
              placeholder="you@example.com"
              className="w-full rounded-lg border border-gray-200 bg-gray-50 px-4 py-2.5 text-xs text-gray-900 placeholder-gray-400 focus:border-brand-300 focus:bg-white focus:outline-none focus:ring-2 focus:ring-brand-100 transition-colors"
            />
            {emailError && <p className="break-words text-[0.625rem] text-red-500">{emailError}</p>}
            <button
              type="submit"
              disabled={emailPending}
              className="w-full rounded-lg bg-brand-600 py-2.5 text-xs font-medium text-on-brand hover:bg-brand-700 disabled:opacity-50 transition-colors"
            >
              {emailPending ? 'Starting…' : 'Start chat'}
            </button>
            <button
              type="button"
              onClick={() => setEmailSubmitted(true)}
              className="w-full text-[0.625rem] text-gray-400 hover:text-gray-600 transition-colors"
            >
              Skip
            </button>
          </form>
        </div>
      ) : (
        <>
          {/* Messages */}
          <div className="flex-1 overflow-y-auto px-4 py-4 space-y-3">
            {messages.length === 0 && (
              <div
                className="-mx-4 -mt-4 bg-gradient-to-b from-brand-50 to-white px-5 pb-5 pt-9 text-center"
                data-testid="welcome-card"
              >
                <div className="mb-3">
                  <WelcomeAvatar logoUrl={logoUrl} />
                </div>
                <h2 className="mx-auto max-w-[20rem] break-words text-base font-semibold leading-snug text-gray-900">
                  {welcome ?? '👋 Hi! How can I help you today?'}
                </h2>
                {starterQuestions.length > 0 && (
                  <div className="mt-5 flex flex-wrap justify-center gap-2" data-testid="starter-questions">
                    {starterQuestions.map((question) => (
                      <button
                        key={question}
                        type="button"
                        onClick={() => sendMessage(question)}
                        disabled={isLoading}
                        className="min-h-11 max-w-full break-words rounded-2xl border border-brand-300 bg-white px-3.5 py-2.5 text-center text-xs font-medium leading-snug text-gray-800 shadow-sm transition-colors hover:border-brand-400 hover:bg-brand-50 focus:outline-none focus-visible:ring-2 focus-visible:ring-brand-400 disabled:opacity-50"
                      >
                        {question}
                      </button>
                    ))}
                  </div>
                )}
              </div>
            )}

            {messages.map((m) => (
              <MessageRow
                key={m.id}
                message={m}
                toolResults={toolResultsByMessage.get(m.id) ?? EMPTY_RESULTS}
                canReply={!isLoading}
                logoUrl={logoUrl}
                feedback={feedbackConfig}
                answerToken={answerTokens[m.id] ?? null}
              />
            ))}

            {showTyping && (
              <div className="flex justify-start">
                <AssistantAvatar logoUrl={logoUrl} />
                <div className="bg-gray-100 rounded-2xl rounded-bl-sm px-3 py-2">
                  <span className="flex gap-1">
                    <span className="h-1.5 w-1.5 rounded-full bg-gray-400 animate-bounce [animation-delay:0ms]" />
                    <span className="h-1.5 w-1.5 rounded-full bg-gray-400 animate-bounce [animation-delay:150ms]" />
                    <span className="h-1.5 w-1.5 rounded-full bg-gray-400 animate-bounce [animation-delay:300ms]" />
                  </span>
                </div>
              </div>
            )}

            {error && (
              <p className="break-words text-center text-xs text-red-400">{error}</p>
            )}

            {sessionExpired && (
              <div className="space-y-3 px-2 text-center" data-testid="session-expired">
                <p className="break-words text-xs leading-relaxed text-gray-600">This chat session timed out. Start a new one to keep going.</p>
                <button
                  type="button"
                  onClick={() => window.location.reload()}
                  className="mx-auto block min-h-11 w-full max-w-[16rem] rounded-lg bg-brand-600 px-4 py-2.5 text-xs font-medium text-on-brand hover:bg-brand-700 transition-colors"
                >
                  Start a new session
                </button>
              </div>
            )}

            {failurePrompt && (
              <div className="rounded-xl border border-brand-100 bg-brand-50 px-3 py-2.5 space-y-2" data-testid="failure-lead-prompt">
                <p className="break-words text-xs text-gray-700">{ON_FAILURE_PROMPT_COPY[failurePrompt.signal]}</p>
                {failureEmailError && (
                  <p className="break-words text-[0.6875rem] text-red-500">{failureEmailError}</p>
                )}
                <form onSubmit={handleFailurePromptSubmit} className="flex flex-col gap-1.5">
                  <input
                    type="email"
                    value={failureEmail}
                    onChange={(e) => setFailureEmail(e.target.value)}
                    placeholder="you@example.com"
                    className="w-full rounded-lg border border-gray-200 bg-white px-2.5 py-1.5 text-xs text-gray-900 placeholder-gray-400 focus:border-brand-300 focus:outline-none focus:ring-2 focus:ring-brand-100 transition-colors"
                  />
                  <div className="flex items-center gap-1.5">
                    <button
                      type="submit"
                      disabled={failureEmailPending || !failureEmail.trim()}
                      className="min-w-[4.5rem] shrink-0 rounded-lg bg-brand-600 px-3 py-1.5 text-center text-[0.6875rem] font-medium text-on-brand hover:bg-brand-700 disabled:opacity-50 transition-colors"
                    >
                      {failureEmailPending ? 'Sending…' : 'Send'}
                    </button>
                    <button
                      type="button"
                      onClick={dismissFailurePrompt}
                      className="shrink-0 text-[0.6875rem] text-gray-400 hover:text-gray-600 transition-colors"
                    >
                      No thanks
                    </button>
                  </div>
                </form>
              </div>
            )}

            <div ref={bottomRef} />
          </div>

          {/* Input */}
          <div className="border-t border-gray-100 px-3 py-3 shrink-0">
            <form onSubmit={handleSubmit} className="flex items-center gap-2">
              <input
                value={input}
                onChange={(e) => setInput(e.target.value)}
                placeholder="Ask a question…"
                className="flex-1 rounded-full border border-gray-200 bg-gray-50 px-4 py-2 text-xs text-gray-900 placeholder-gray-400 focus:border-brand-300 focus:bg-white focus:outline-none focus:ring-2 focus:ring-brand-100 transition-colors"
                disabled={isLoading}
              />
              <button
                type="submit"
                disabled={isLoading || !input.trim()}
                className="flex h-8 w-8 shrink-0 items-center justify-center rounded-full bg-brand-600 text-on-brand disabled:opacity-40 hover:bg-brand-700 transition-colors"
              >
                <svg className="h-3.5 w-3.5 rotate-90" viewBox="0 0 24 24" fill="currentColor">
                  <path d="M2.01 21L23 12 2.01 3 2 10l15 2-15 2z"/>
                </svg>
              </button>
            </form>
            {showBranding && (
              <p className="text-center text-[0.625rem] text-gray-300 mt-2">Powered by answerLoops</p>
            )}
          </div>
        </>
      )}
    </div>
    </WidgetActionsProvider>
  )
}
